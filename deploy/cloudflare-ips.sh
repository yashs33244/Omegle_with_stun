#!/usr/bin/env sh
# Writes the gateway's Cloudflare include files from Cloudflare's published
# ranges (https://www.cloudflare.com/ips-v4 and https://www.cloudflare.com/ips-v6).
#
#   sh deploy/cloudflare-ips.sh [nginx-dir]      (default: deploy/nginx next to this script)
#
# Output, both included by gateway.conf:
#   cloudflare-ips.conf   "<cidr> cloudflare;" lines for the gateway's geo map.
#                         The gateway believes CF-Connecting-IP and CF-IPCountry
#                         only from these addresses.
#   cloudflare-only.conf  CLOUDFLARE_ONLY=true: refuse (403) requests from public
#                         addresses that are not Cloudflare, so nobody can skip
#                         the proxy (and the country blocklist) by calling the
#                         origin directly. Otherwise: no rule.
#
# deploy/deploy.sh runs this on the host at every deploy when CLOUDFLARE_ONLY
# is true. A committed snapshot of the ranges ships with the repo; refresh it
# with `sh deploy/cloudflare-ips.sh` and commit the result. If a download fails
# or looks wrong the existing list is kept.
#
# Environment:
#   CLOUDFLARE_ONLY      true to write the enforcing rule (default false)
#   CLOUDFLARE_IPS_URL   base URL of the lists (default https://www.cloudflare.com)
set -eu

dir=${1:-"$(cd "$(dirname "$0")" && pwd)/nginx"}
base=${CLOUDFLARE_IPS_URL:-https://www.cloudflare.com}
only=${CLOUDFLARE_ONLY:-false}

log() { printf '[cloudflare-ips] %s\n' "$*"; }

[ -d "$dir" ] || { log "no such directory: $dir" >&2; exit 1; }

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

fetch() {
  curl -fsS --max-time 15 --retry 2 "$base/$1" -o "$tmp/$1"
}

# Every line must be a CIDR of the right family, and the lists must not be
# implausibly short (an error page or an empty answer must never become the
# allow list).
valid() {
  file=$1 pattern=$2 min=$3
  [ -s "$file" ] || return 1
  count=$(grep -c . "$file" || true)
  [ "$count" -ge "$min" ] || return 1
  ! grep -v -E "$pattern" "$file" | grep -q .
}

v4='^[0-9]{1,3}(\.[0-9]{1,3}){3}/[0-9]{1,2}$'
v6='^[0-9a-fA-F:]+/[0-9]{1,3}$'

if fetch ips-v4 && fetch ips-v6 &&
  tr -d '\r' <"$tmp/ips-v4" >"$tmp/v4" && tr -d '\r' <"$tmp/ips-v6" >"$tmp/v6" &&
  valid "$tmp/v4" "$v4" 5 && valid "$tmp/v6" "$v6" 3; then
  {
    echo "# Generated by deploy/cloudflare-ips.sh from $base/ips-v4 and /ips-v6."
    echo "# geo entries for gateway.conf. Do not edit by hand; rerun the script."
    grep . "$tmp/v4" | sed 's/$/ cloudflare;/'
    grep . "$tmp/v6" | sed 's/$/ cloudflare;/'
  } >"$tmp/cloudflare-ips.conf"
  mv -f "$tmp/cloudflare-ips.conf" "$dir/cloudflare-ips.conf"
  log "wrote $(grep -c ' cloudflare;' "$dir/cloudflare-ips.conf") ranges to $dir/cloudflare-ips.conf"
elif [ -s "$dir/cloudflare-ips.conf" ]; then
  log "WARNING: could not download valid lists; keeping the existing $dir/cloudflare-ips.conf"
else
  log "could not download valid lists and no existing list to keep" >&2
  exit 1
fi

if [ "$only" = "true" ]; then
  cat >"$tmp/cloudflare-only.conf" <<'EOF'
# Generated by deploy/cloudflare-ips.sh with CLOUDFLARE_ONLY=true.
# Requests from public addresses that are not Cloudflare are refused. Health
# checks from the host and the compose network ($chizzy_peer = local) pass.
if ($chizzy_peer = public) {
    return 403;
}
EOF
  log "CLOUDFLARE_ONLY=true: the gateway refuses requests that did not come through Cloudflare"
else
  cat >"$tmp/cloudflare-only.conf" <<'EOF'
# Generated by deploy/cloudflare-ips.sh. CLOUDFLARE_ONLY is not true, so the
# gateway accepts requests from any address (no rule).
EOF
  log "CLOUDFLARE_ONLY is not true: no origin restriction"
fi
mv -f "$tmp/cloudflare-only.conf" "$dir/cloudflare-only.conf"
